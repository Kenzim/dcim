// Package ganesha renders NFS-Ganesha configuration for one tenant and runs
// Ganesha in a container inside the tenant's network namespace.
package ganesha

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"
)

// Fixed ports in the tenant namespace: NFS, the v3 MOUNT service and rpcbind.
const (
	NFSPort     = 2049
	MountPort   = 20048
	RPCBindPort = 111
)

type Config struct {
	TenantID   int64
	BindAddr   netip.Addr
	UserID     string // cephx id without "client."
	Filesystem string
	Exports    []Export
	// RADOS keeps NFSv4 client recovery state in RADOS, so a Ganesha started
	// on another node runs the grace period for the same clients. Nil keeps
	// recovery state in the container's local recovery directory.
	RADOS *RADOSRecovery
}

// RADOSRecovery configures the rados_ng recovery backend.
type RADOSRecovery struct {
	// UserID is the cephx id (without "client.") the recovery database is
	// opened with; empty uses the tenant's own Config.UserID.
	UserID        string
	Pool          string
	Namespace     string
	NodeID        string
	LeaseLifetime int64
	GracePeriod   int64
}

type Export struct {
	ID       int64
	Path     string // CephFS path of the subvolume
	Pseudo   string // NFSv4 pseudo path, "/<share name>"
	Clients  []string
	ReadOnly bool
}

// Render returns the core part (changes need a restart) and the export part
// (reloaded with SIGHUP). The file on disk is core followed by exports.
func Render(c Config) (core, exports string) {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by the Rackflow storage runner for tenant %d. Changes are overwritten.\n", c.TenantID)
	b.WriteString("NFS_CORE_PARAM {\n")
	// NFSv3 is offered next to 4.1 for clients that only speak v3 (the
	// Windows NFS client). Its MOUNT service is on a fixed port and also
	// answers over UDP, which Windows uses; NFS itself stays TCP only. v3
	// clients mount the same /<share> pseudo path as v4. NLM is off, so v3
	// clients mount with nolock.
	b.WriteString("\tProtocols = 3, 4;\n")
	fmt.Fprintf(&b, "\tNFS_Port = %d;\n", NFSPort)
	fmt.Fprintf(&b, "\tMNT_Port = %d;\n", MountPort)
	fmt.Fprintf(&b, "\tBind_addr = %s;\n", c.BindAddr)
	b.WriteString("\tEnable_UDP = Mount;\n")
	b.WriteString("\tMount_Path_Pseudo = true;\n")
	b.WriteString("\tEnable_NLM = false;\n")
	b.WriteString("\tEnable_RQUOTA = false;\n")
	b.WriteString("}\n\n")
	b.WriteString("NFSv4 {\n")
	if c.RADOS != nil {
		b.WriteString("\tRecoveryBackend = rados_ng;\n")
	} else {
		b.WriteString("\tRecoveryBackend = fs;\n")
	}
	// NFS 4.2 is not offered: Ganesha's READ_PLUS replies over FSAL_CEPH make
	// Linux clients fail reads with EIO. Clients negotiate down to 4.1.
	b.WriteString("\tMinor_Versions = 1;\n")
	if r := c.RADOS; r != nil {
		fmt.Fprintf(&b, "\tLease_Lifetime = %d;\n", r.LeaseLifetime)
		fmt.Fprintf(&b, "\tGrace_Period = %d;\n", r.GracePeriod)
	}
	b.WriteString("}\n\n")
	if r := c.RADOS; r != nil {
		b.WriteString("RADOS_KV {\n")
		fmt.Fprintf(&b, "\tceph_conf = %q;\n", CephDir+"/ceph.conf")
		userID := c.UserID
		if r.UserID != "" {
			userID = r.UserID
		}
		fmt.Fprintf(&b, "\tuserid = %q;\n", userID)
		fmt.Fprintf(&b, "\tpool = %q;\n", r.Pool)
		fmt.Fprintf(&b, "\tnamespace = %q;\n", r.Namespace)
		fmt.Fprintf(&b, "\tnodeid = %q;\n", r.NodeID)
		b.WriteString("}\n\n")
	}
	b.WriteString("EXPORT_DEFAULTS {\n")
	b.WriteString("\tAccess_Type = None;\n")
	b.WriteString("\tSquash = root_squash;\n")
	b.WriteString("}\n")
	core = b.String()

	sorted := append([]Export(nil), c.Exports...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })
	var e strings.Builder
	for _, x := range sorted {
		access := "RW"
		if x.ReadOnly {
			access = "RO"
		}
		e.WriteString("\nEXPORT {\n")
		fmt.Fprintf(&e, "\tExport_Id = %d;\n", x.ID)
		fmt.Fprintf(&e, "\tPath = %q;\n", x.Path)
		fmt.Fprintf(&e, "\tPseudo = %q;\n", x.Pseudo)
		e.WriteString("\tProtocols = 3, 4;\n")
		e.WriteString("\tTransports = TCP;\n")
		e.WriteString("\tAccess_Type = None;\n")
		e.WriteString("\tSquash = root_squash;\n")
		e.WriteString("\tSecType = sys;\n")
		e.WriteString("\tFSAL {\n")
		e.WriteString("\t\tName = CEPH;\n")
		fmt.Fprintf(&e, "\t\tUser_Id = %q;\n", c.UserID)
		fmt.Fprintf(&e, "\t\tFilesystem = %q;\n", c.Filesystem)
		e.WriteString("\t}\n")
		if len(x.Clients) > 0 {
			e.WriteString("\tCLIENT {\n")
			fmt.Fprintf(&e, "\t\tClients = %s;\n", strings.Join(x.Clients, ", "))
			fmt.Fprintf(&e, "\t\tAccess_Type = %s;\n", access)
			e.WriteString("\t\tSquash = root_squash;\n")
			// Squashed root writes as nobody:nogroup rather than Ganesha's default
			// of -2, which clients would show as uid 4294967294.
			e.WriteString("\t\tAnonymous_Uid = 65534;\n")
			e.WriteString("\t\tAnonymous_Gid = 65534;\n")
			e.WriteString("\t}\n")
		}
		e.WriteString("}\n")
	}
	return core, e.String()
}
